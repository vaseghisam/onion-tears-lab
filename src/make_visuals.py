#!/usr/bin/env python3
"""Render article figures from checked numerical outputs.

Run from any working directory. No field values or numerical outcomes are
recomputed here: those are read from results generated by run_simulations.py.
The chemistry and remedy panels are evidence summaries, not measurements.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib import animation, colors
from matplotlib.patches import FancyArrowPatch, FancyBboxPatch
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
RESULTS = ROOT / "results"
CHARCOAL = "#202A30"
MUTED = "#59656D"
PALE = "#E2E7EA"
BLUE = "#1F658C"
ORANGE = "#B56330"


def apply_style():
    plt.rcParams.update({
        "font.family": "DejaVu Sans", "font.size": 11,
        "text.color": CHARCOAL, "axes.labelcolor": CHARCOAL,
        "axes.edgecolor": MUTED, "xtick.color": MUTED, "ytick.color": MUTED,
        "axes.spines.top": False, "axes.spines.right": False,
        "figure.facecolor": "white", "axes.facecolor": "white",
        "savefig.facecolor": "white", "svg.fonttype": "none",
        "mathtext.fontset": "dejavusans", "axes.titleweight": "medium",
    })


def save_pair(fig, stem):
    ASSETS.mkdir(exist_ok=True)
    for extension in ("png", "svg"):
        fig.savefig(ASSETS / f"{stem}.{extension}", dpi=210,
                    facecolor="white", bbox_inches="tight", pad_inches=.16)


def header(fig, title, subtitle, x=.055, y=.95):
    fig.text(x, y, title, fontsize=22, weight="bold", ha="left", va="top")
    fig.text(x, y-.068, subtitle, fontsize=11.5, color=MUTED,
             ha="left", va="top")


def chemistry():
    """Verified pathway, using catalysts on arrows rather than as products."""
    fig = plt.figure(figsize=(13.4, 4.2))
    ax = fig.add_axes([.015, .06, .97, .68])
    ax.set(xlim=(0, 1), ylim=(0, 1))
    ax.axis("off")
    header(fig, "From cut tissue to reflex tears",
           "Cutting brings the precursor isoalliin into contact with alliinase.",
           y=.95)
    centres = [.115, .375, .635, .885]
    labels = ["Isoalliin", "1-Propenesulfenic\nacid",
              "syn-Propanethial\nS-oxide", "Eye irritation\nand reflex tears"]
    details = ["Sulfur precursor", "Reaction intermediate",
               "Lachrymatory factor", "Response to exposure"]
    widths = [.190, .190, .190, .190]
    for i, (x, label, detail, width) in enumerate(zip(centres, labels, details, widths)):
        rect = FancyBboxPatch((x-width/2, .33), width, .28,
                              boxstyle="round,pad=0.015,rounding_size=0.012",
                              facecolor="#F4F7F9" if i == 2 else "white",
                              edgecolor=BLUE if i == 2 else PALE,
                              linewidth=1.4)
        ax.add_patch(rect)
        ax.text(x, .47, label, ha="center", va="center", fontsize=12.8,
                weight="medium", linespacing=1.35)
        ax.text(x, .205, detail, ha="center", va="center", fontsize=10,
                color=MUTED)
    catalysts = ["alliinase", "LF synthase", "transport\nthrough air"]
    for i in range(3):
        xa = centres[i]+widths[i]/2+.017
        xb = centres[i+1]-widths[i+1]/2-.017
        ax.add_patch(FancyArrowPatch((xa, .47), (xb, .47), arrowstyle="-|>",
                                    mutation_scale=13, color=CHARCOAL,
                                    linewidth=1.2))
        ax.text((xa+xb)/2, .72, catalysts[i], ha="center", va="center",
                fontsize=10.5, linespacing=1.35,
                color=BLUE if i < 2 else MUTED)
    ax.plot([.035, .745], [.90, .90], color=PALE, lw=1)
    ax.text(.035, .925, "CHEMISTRY IN DAMAGED TISSUE", fontsize=9,
            color=MUTED, va="bottom", weight="bold")
    fig.text(.055, .045,
             "Enzyme names label the reactions. Coproducts and competing reactions omitted. Schematic; molecular structures and distances not shown.",
             fontsize=9.1, color=MUTED)
    save_pair(fig, "figure_02_chemistry")
    plt.close(fig)


def load_csv(path):
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


